// Arithmetic operators are used to perform arithmetic operations on numbers
let a = 10;
let b = 5;

let sum = a + b; // addition
let sub = a-b;
let mul = a*b;
let div = a/b;
console.log("Sum: " + sum);
console.log("Subtraction: " + sub);
console.log("Multiplication: " + mul);
console.log("Division: " + div);    

// Modulus operator returns the remainder of a division operation
let mod = a % b;
console.log("Modulus: " + mod); // Output: 0
console.log("Modulus: " + (a % 3)); // Output: 1

// n%2==0 means n is even, n%2==1 means n is odd
// exponentiation operator (**), power 2^3 (8)
console.log("Exponentiation: " + (2**3));
console.log("Exponentiation: " + (a**b)); 