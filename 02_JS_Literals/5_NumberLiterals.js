let age = '20';
console.log(age);

let age1 = 'Tejas'; //String literal
console.log(age1);

let age2 = "Teju";
console.log(age2);

let isStudent = true; //Boolean literal
console.log(isStudent);

let pi = 3.14; //Number literal
console.log(pi);

let nullValue = null; //Null literal assigned to variable nullValue
console.log(nullValue);

let undefinedValue; //Undefined literal (implicitly)
console.log(undefinedValue);

//typeof operator - tells what type of data is stored in the variable
console.log(typeof age);
console.log(typeof age1);
console.log(typeof age2);
console.log(typeof isStudent);
console.log(typeof pi);
console.log(typeof nullValue);
console.log(typeof undefinedValue); 