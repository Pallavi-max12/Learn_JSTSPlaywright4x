/*
  SIMPLE DEFINITIONS:

  undefined  ->  A variable exists, but it has not been assigned any value yet.
                 JavaScript itself sets this automatically.

  null       ->  A variable exists, but the developer explicitly assigns 
                "no value" or "empty".
                 It is intentional absence of any value.
*/
//==============
// UNDEFINEd
//==============
let userName; //undefined literal (implicitly)
console.log(userName); 
console.log(typeof userName); 

let x ;
x= 10;
console.log(x);

//==============
// NULL
//==============
let profilePicture = null;      //null literal assigned to variable profilePicture
console.log(profilePicture); 
console.log(typeof profilePicture);


