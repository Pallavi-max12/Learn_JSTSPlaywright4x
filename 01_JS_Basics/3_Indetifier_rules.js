
//Naming Conventions
//1. Camel Case (standard for JS variable and functions)
let firstName = "John";
console.log(firstName);

let isLoggedIn = true;
console.log(isLoggedIn);

//2. Pascal Case (Standard for JS constructors and classes)
let UserName = "John1";
console.log(UserName);

let UserAge = 20;
console.log(UserAge);

//3. Snake Case (underscore separated words)
let last_name = "mathew";
console.log(last_name);

let is_logged_in = true;
console.log(is_logged_in);

//4. Screaming Snake Case (Constants,uppercase underscore separated words)
const MAX_HEIGHT = 100;
console.log(MAX_HEIGHT);

const API_KEY = "1234567890";
console.log(API_KEY);

//5. Hungarian Notation (prefixes to indicate type of variable) 
let strName = "John"; // str for string
console.log(strName);

let numAge = 20; // num for number
console.log(numAge);

let bolLoggedIn = true; // bol for boolean
console.log(bolLoggedIn);   

